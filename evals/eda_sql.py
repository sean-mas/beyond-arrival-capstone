#!/usr/bin/env python3
"""The SQL half of the EDA, run against pgvector.

    PYTHONPATH=src python3 evals/eda_sql.py

`docs/requirements.md` requires the EDA "in Python and SQL". `evals/eda.py` is
the Python half and its docstring claimed the SQL half existed; it did not, and
the requirement was unmet while a docstring said otherwise. This is that half,
written as SQL rather than as pandas over a dataframe, because the corpus
genuinely lives in Postgres now and the near-duplicate query is one the
database does better than numpy: `<=>` is a pgvector operator and the join is
over the index.

Five queries, each answering something a reviewer would ask about the corpus.
"""

from __future__ import annotations

import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "src"))

from sqlalchemy import create_engine, text  # noqa: E402

from companion.config import settings  # noqa: E402

OUT = pathlib.Path(__file__).resolve().parents[1] / "delivery" / "eda"

QUERIES: list[tuple[str, str, str]] = [
    (
        "Chunk length by strand",
        "Is one strand systematically wordier? A strand of long chunks retrieves "
        "worse, because one chunk then covers several ideas.",
        """
        SELECT strand,
               count(*)                                        AS chunks,
               min(array_length(regexp_split_to_array(chunk_text, '\\s+'), 1))  AS min_words,
               round(avg(array_length(regexp_split_to_array(chunk_text, '\\s+'), 1)))
                                                               AS avg_words,
               max(array_length(regexp_split_to_array(chunk_text, '\\s+'), 1))  AS max_words
        FROM card_chunks WHERE tenant_id = 'global'
        GROUP BY strand ORDER BY chunks DESC
        """,
    ),
    (
        "Coverage: strand against audience",
        "Where the corpus is thin. A cell with one card is a cell where any "
        "question lands on the same chunk whatever it asks.",
        """
        SELECT strand, audience, count(DISTINCT card_id) AS cards
        FROM card_chunks WHERE tenant_id = 'global'
        GROUP BY strand, audience ORDER BY cards DESC
        """,
    ),
    (
        "Journey months with no card",
        "The product promises months three to twelve. This asks which of those "
        "months the corpus actually covers.",
        """
        WITH months AS (SELECT generate_series(0, 24) AS m)
        SELECT m AS journey_month,
               count(DISTINCT c.card_id) AS cards
        FROM months LEFT JOIN card_chunks c
          ON c.tenant_id = 'global' AND m BETWEEN c.journey_from AND c.journey_to
        GROUP BY m ORDER BY cards ASC, m LIMIT 8
        """,
    ),
    (
        "Nearest neighbours across cards",
        "Chunks from different cards that sit close together. These are the "
        "pairs a retriever has to choose between, and the reason the top-to-"
        "second margin is 0.017.",
        """
        SELECT a.chunk_id AS chunk_a, b.chunk_id AS chunk_b,
               round((1 - (a.embedding <=> b.embedding))::numeric, 3) AS similarity
        FROM card_chunks a JOIN card_chunks b
          ON a.tenant_id = b.tenant_id AND a.card_id < b.card_id
        WHERE a.tenant_id = 'global'
        ORDER BY a.embedding <=> b.embedding
        LIMIT 5
        """,
    ),
    (
        "Tenant isolation, as the database sees it",
        "The white-label promise as one row count per tenant. Anything other "
        "than a single 'global' tenant here is test residue in a real store.",
        """
        SELECT tenant_id, count(*) AS chunks, count(DISTINCT card_id) AS cards
        FROM card_chunks GROUP BY tenant_id ORDER BY chunks DESC
        """,
    ),
]


def render(rows: list, keys: list[str]) -> str:
    head = "| " + " | ".join(keys) + " |"
    rule = "|" + "|".join("---" for _ in keys) + "|"
    body = ["| " + " | ".join(str(v) for v in r) + " |" for r in rows]
    return "\n".join([head, rule, *body])


def main() -> int:
    engine = create_engine(settings.database_url, future=True)
    parts: list[str] = [
        "# EDA, SQL half\n",
        "Generated by `evals/eda_sql.py` against pgvector. The Python half is "
        "`evals/eda.py` and its output is in this folder's `README.md`.\n",
    ]
    with engine.connect() as conn:
        for title, why, sql in QUERIES:
            result = conn.execute(text(sql))
            keys = list(result.keys())
            rows = result.all()
            parts.append(f"## {title}\n\n{why}\n")
            parts.append("```sql" + sql.rstrip() + "\n```\n")
            parts.append(render(rows, keys) + "\n")
            print(f"\n{title}\n" + render(rows, keys))

    (OUT / "README-sql.md").write_text("\n".join(parts))
    print(f"\n  written to {OUT / 'README-sql.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
